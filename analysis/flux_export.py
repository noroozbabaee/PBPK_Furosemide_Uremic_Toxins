# -*- coding: utf-8 -*-
"""Print and write Figure 4 flux tables (mass balance + filt vs secretion).

Share definition for the paper:
  secretion = apical secretion
  filt_share = filtration / (filtration + apical) × 100
  secr_share = 100 − filt_share

At no-drug SS, basolateral uptake ≈ apical secretion (ratio ≈ 1).
"""
from __future__ import annotations

import os
from typing import Dict, Optional

SPECIES = ("IS", "pCS", "HA", "DRUG")
DISPLAY = {"IS": "IS", "pCS": "pCS", "HA": "HA", "DRUG": "Furosemide"}
SCENARIO_ORDER = (
    "Healthy No Furosemide",
    "Healthy With Furosemide",
    "CKD-5 No Furosemide",
    "CKD-5 With Furosemide",
)


def _f(flux: dict, key: str, sp: str) -> float:
    return float(flux.get(key, {}).get(sp, 0.0) or 0.0)


def _shares(flux: dict, sp: str) -> dict:
    filt = abs(_f(flux, "filtration", sp))
    pas = abs(_f(flux, "basolateral_passive", sp))
    up = abs(_f(flux, "basolateral_uptake", sp))
    ap = abs(_f(flux, "apical_secretion", sp))
    tot = filt + pas + up + ap
    two = filt + ap
    return {
        "filt": filt, "pass": pas, "uptake": up, "apical": ap, "tot": tot,
        "pct_filt": 100.0 * filt / tot if tot > 0 else float("nan"),
        "pct_pass": 100.0 * pas / tot if tot > 0 else float("nan"),
        "pct_up": 100.0 * up / tot if tot > 0 else float("nan"),
        "pct_ap": 100.0 * ap / tot if tot > 0 else float("nan"),
        "filt_vs_secr": 100.0 * filt / two if two > 0 else float("nan"),
        "secr_vs_filt": 100.0 * ap / two if two > 0 else float("nan"),
        "up_over_ap": up / ap if ap > 1e-18 else float("nan"),
    }


def export_flux_results(flux_data_all: Dict[str, dict], outdir: str,
                        time_window, pub_dir: Optional[str] = None) -> str:
    os.makedirs(outdir, exist_ok=True)
    lines = []
    t0, t1 = time_window
    print(f"\n=== Figure 4 fluxes (mean t = {t0:.0f}–{t1:.0f} h) ===")
    print("Mass balance: no-drug uptake/apical should be ≈ 1.00")
    print("Paper split: Filtration % = filt / (filt + apical)")

    tex = [
        r"% Auto-generated by flux_export.py — do not edit by hand",
        r"\begin{tabular}{llrrrr}",
        r"Scenario & Species & Filt.\ (\%) & Secr.\ (\%) & Uptake/apical & Notes \\",
        r"\hline",
    ]

    for scen in SCENARIO_ORDER:
        if scen not in flux_data_all:
            continue
        flx = flux_data_all[scen]
        print(f"\n{scen}")
        nodrug = "No Furosemide" in scen
        for sp in SPECIES:
            s = _shares(flx, sp)
            name = DISPLAY[sp]
            if s["tot"] <= 0 and sp == "DRUG" and nodrug:
                print(f"  {name}: (no drug)")
                continue
            print(
                f"  {name}: Filt={s['pct_filt']:.1f}%  Pass={s['pct_pass']:.1f}%  "
                f"Uptake={s['pct_up']:.1f}%  Apical={s['pct_ap']:.1f}%  "
                f"| paper filt/secr={s['filt_vs_secr']:.1f}/{s['secr_vs_filt']:.1f}%  "
                f"| uptake/apical={s['up_over_ap']:.2f}"
            )
            if nodrug and sp != "DRUG":
                ok = abs(s["up_over_ap"] - 1.0) < 0.15 if s["up_over_ap"] == s["up_over_ap"] else False
                tag = "OK" if ok else "FAIL SS"
                print(f"    mass-balance {tag}")
            note = ""
            if nodrug and sp != "DRUG":
                note = r"$\approx 1$" if abs(s["up_over_ap"] - 1.0) < 0.15 else "check"
            tex.append(
                f"{scen} & {name} & {s['filt_vs_secr']:.1f} & {s['secr_vs_filt']:.1f} & "
                f"{s['up_over_ap']:.2f} & {note} \\\\"
            )
            lines.append(
                f"{scen}\t{sp}\t{s['filt']:.6g}\t{s['apical']:.6g}\t"
                f"{s['uptake']:.6g}\t{s['filt_vs_secr']:.2f}\t{s['up_over_ap']:.4f}\n"
            )

    tex.append(r"\end{tabular}")
    tex_path = os.path.join(outdir, "flux_numbers.tex")
    with open(tex_path, "w", encoding="utf-8") as f:
        f.write("\n".join(tex) + "\n")
    tsv_path = os.path.join(outdir, "flux_numbers.tsv")
    with open(tsv_path, "w", encoding="utf-8") as f:
        f.write("scenario\tspecies\tfilt\tapical\tuptake\tfilt_share_pct\tup_over_ap\n")
        f.writelines(lines)
    print(f"\nWrote flux_numbers.tex → {tex_path}")
    print(f"Wrote flux_numbers.tsv → {tsv_path}")
    if pub_dir:
        os.makedirs(pub_dir, exist_ok=True)
        pub_tex = os.path.join(pub_dir, "flux_numbers.tex")
        with open(pub_tex, "w", encoding="utf-8") as f:
            f.write("\n".join(tex) + "\n")
        print(f"Wrote flux_numbers.tex → {pub_tex}")
    return tex_path
